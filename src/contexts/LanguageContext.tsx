const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguage] = useState<Language>('ru');

  const t = (key: TranslationKey): string => {
    const currentTranslations = translations[language] as Record<string, string>;
    const russianTranslations = translations.ru as Record<string, string>;
    const englishTranslations = translations.en as Record<string, string>;

    if (currentTranslations && currentTranslations[key]) {
      return currentTranslations[key];
    }

    if (russianTranslations && russianTranslations[key]) {
      return russianTranslations[key];
    }

    if (englishTranslations && englishTranslations[key]) {
      return englishTranslations[key];
    }

    if (process.env.NODE_ENV !== 'production') {
      console.warn(`[i18n] Missing translation for key: ${key}`);
    }

    return key;
  };

  const translate = (input: TranslateArgs | string): string => {
    if (typeof input === 'string') {
      return t(input);
    }

    const { ru, uz, en, de } = input;
    if (language === 'ru') {
      return ru;
    }
    if (language === 'uz') {
      return uz;
    }
    if (language === 'de' && de) {
      return de;
    }
    return en ?? ru;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, translate }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};