export const LanguageProvider: React.FC<{ children: ReactNode }> = ({
  children,
}) => {
  const [language, setLanguage] = useState<Language>("ru");

  const t = (key: TranslationKey): string => {
    const currentTranslations = translations[language] as Record<
      string,
      string
    >;
    const russianTranslations = translations.ru as Record<string, string>;
    const englishTranslations = translations.en as Record<string, string>;

    if (currentTranslations && currentTranslations[key]) {
      return currentTranslations[key];
    }

    if (russianTranslations && russianTranslations[key]) {
      return russianTranslations[key];
    }

    if (englishTranslations && englishTranslations[key]) {
      return englishTranslations[key];
    }

    if (process.env.NODE_ENV !== "production") {
      console.warn(`[i18n] Missing translation for key: ${key}`);
    }

    return key;
  };

  const translate = (input: TranslateArgs | string): string => {
    if (typeof input === "string") {
      return t(input);
    }

    const { ru, uz, en, de } = input;
    if (language === "ru") {
      return ru;
    }
    if (language === "uz") {
      return uz;
    }
    if (language === "de" && de) {
      return de;
    }
    return en ?? ru;
  };

  /**
   * Returns correct plural form based on count and language.
   * Russian: 1 день, 2-4 дня, 5-20 дней, 21 день, 22-24 дня, etc.
   * Other languages: simpler rules (1=one, rest=many)
   */
  const pluralize = (
    count: number,
    one: string,
    few: string,
    many: string,
  ): string => {
    const absCount = Math.abs(count);

    if (language === "ru") {
      // Russian pluralization rules
      const mod10 = absCount % 10;
      const mod100 = absCount % 100;

      if (mod10 === 1 && mod100 !== 11) {
        return one; // 1, 21, 31, ... (but not 11)
      }
      if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) {
        return few; // 2-4, 22-24, 32-34, ... (but not 12-14)
      }
      return many; // 0, 5-20, 25-30, ...
    }

    // German: 1 = singular, rest = plural
    if (language === "de") {
      return absCount === 1 ? one : many;
    }

    // English and Uzbek: 1 = singular, rest = plural
    return absCount === 1 ? one : many;
  };

  return (
    <LanguageContext.Provider
      value={{ language, setLanguage, t, translate, pluralize }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
};
